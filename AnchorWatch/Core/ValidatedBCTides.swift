    struct Record {
        let chsID: String
        let code: String
        let name: String
        let latitude: Double
        let longitude: Double
        let meanWaterLevel: Double
        let constituents: [HarmonicConstituent]
        var predictor: SlackwaterKit.Station {
            SlackwaterKit.Station(constituents: constituents, offset: meanWaterLevel)
        }
    }

    static func record(for station: TideStation) -> Record? {
        guard station.source == TideStation.chs,
              CLLocationCoordinate2DIsValid(station.coordinate),
              let record = records.first(where: { $0.chsID == station.id }),
              Geo.distance(station.coordinate, CLLocationCoordinate2D(latitude: record.latitude, longitude: record.longitude)) < 2_000
        else { return nil }
        return record
    }

    static func modelID(for station: TideStation) -> String? {
        record(for: station).map { revision + ":" + $0.code }
    }

    static func height(at time: Date, station: TideStation) -> Double? {
        guard time.timeIntervalSince1970.isFinite, let record = record(for: station) else { return nil }
        // Linear interpolation over at most one minute; do not round the requested instant.
        let points = record.predictor.heights(from: time, to: time, step: 60)
        guard let first = points.first, let last = points.last else { return nil }
        let span = last.time.timeIntervalSince(first.time)
        if span == 0 { return first.height }
        let fraction = time.timeIntervalSince(first.time) / span
        return first.height + (last.height - first.height) * fraction
    }

